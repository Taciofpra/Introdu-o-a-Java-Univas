/* Crie um programa que use um loop for para exibir uma
contagem regressiva de 10 a 1. Ao final, imprima a mensagem
"Lançar!". */
public class lancamento {
    public static void main(String[] args){
        for(int i=10;i>0;i--){
            System.out.println(i+"..");
        }
        System.out.println("Lançar!");
    }
}
